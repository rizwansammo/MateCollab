// Generates everything derived from the contract sources:
//   openapi/**/*.yaml  →  src/generated/openapi.json   (bundled document; used by Go contract tests)
//                      →  src/generated/openapi.ts     (TypeScript types, openapi-typescript)
//   events/*.json      →  src/generated/events.ts      (TypeScript types, json-schema-to-typescript)
// `--check` regenerates in memory and fails if the committed output is stale.

import { spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';

const require = createRequire(import.meta.url);
const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(PKG, 'src', 'generated');
const CHECK = process.argv.includes('--check');
const BANNER = '// Generated by packages/contracts/scripts/generate.mjs. Do not edit; run `pnpm gen`.\n';

function bundleOpenAPI() {
  const cli = path.join(path.dirname(require.resolve('@redocly/cli/package.json')), 'bin', 'cli.js');
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'mc-openapi-'));
  try {
    const target = path.join(tmp, 'openapi.json');
    const res = spawnSync(process.execPath, [cli, 'bundle', 'openapi/openapi.yaml', '--output', target], {
      cwd: PKG,
      encoding: 'utf8',
      env: { ...process.env, REDOCLY_TELEMETRY: 'off', REDOCLY_SUPPRESS_UPDATE_NOTICE: 'true' },
    });
    if (res.status !== 0) throw new Error(`redocly bundle failed:\n${res.stdout}${res.stderr}`);
    return JSON.parse(readFileSync(target, 'utf8'));
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

async function eventTypes() {
  const dir = path.join(PKG, 'events');
  const parts = [];
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith('.schema.json'))
    .sort()) {
    const schema = JSON.parse(readFileSync(path.join(dir, file), 'utf8'));
    parts.push(
      await compile(schema, schema.title, {
        bannerComment: '',
        additionalProperties: false,
        unknownAny: true,
        format: true,
        style: { singleQuote: true, printWidth: 110 },
      }),
    );
  }
  return BANNER + '\n' + parts.join('\n');
}

const bundled = bundleOpenAPI();
const outputs = {
  'openapi.json': JSON.stringify(bundled, null, 2) + '\n',
  'openapi.ts': BANNER + '\n' + astToString(await openapiTS(bundled, { alphabetize: true })),
  'events.ts': await eventTypes(),
};

const normalise = (s) => s.replace(/\r\n/g, '\n');
if (CHECK) {
  const stale = Object.entries(outputs)
    .filter(([name, content]) => {
      const file = path.join(OUT, name);
      return !existsSync(file) || normalise(readFileSync(file, 'utf8')) !== normalise(content);
    })
    .map(([name]) => name);
  if (stale.length) {
    console.error(`Generated contract files are stale: ${stale.join(', ')}. Run \`pnpm gen\` and commit.`);
    process.exit(1);
  }
  console.log('Generated contract files are up to date.');
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) writeFileSync(path.join(OUT, name), content, 'utf8');
  console.log(`Generated ${Object.keys(outputs).join(', ')} in src/generated/`);
}
